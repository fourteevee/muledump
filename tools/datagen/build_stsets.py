"""Build lib/stsets.js (the ST set list for the ST Set Collection tracker) from RotMG Exalt client data.

usage: build_stsets.py <gamedata dir> <output stsets.js>

gamedata dir: TextAssets exported from resources.assets (needs equipmentsets, players and the equip* XML files)

An ST set is an equipment set whose pieces are all labelled ST (the 4-piece class sets, plus a couple of
5-piece ones). Themed reskin sets without the ST label and the multi-item "core" groupings are skipped.
"""
import json, os, sys, time
import xml.etree.ElementTree as ET

GD, OUT = sys.argv[1:3]

items = {}
for fn in sorted(os.listdir(GD)):
    if not fn.startswith('equip'):
        continue
    try:
        root = ET.parse(os.path.join(GD, fn)).getroot()
    except ET.ParseError:
        continue
    for o in root.iter('Object'):
        if o.find('Item') is not None:
            items.setdefault(int(o.get('type'), 16), o)


def labels(o):
    return set((o.findtext('Labels') or '').split(','))


def name(o):
    return o.findtext('DisplayId') or o.get('id')


def slot(o):
    return int(o.findtext('SlotType') or 0)


#  other item ids with the same name and slot count as the same piece (e.g. alternate copies of a piece)
by_name = {}
for iid, o in items.items():
    by_name.setdefault((name(o), slot(o)), []).append(iid)

#  class lookup by (weapon slot, ability slot)
classes = []
for o in ET.parse(os.path.join(GD, 'players')).getroot().iter('Object'):
    if o.findtext('Class') == 'Player':
        st = [int(x) for x in o.findtext('SlotTypes').split(',')[:4]]
        classes.append((o.get('id'), st[0], st[1], int(o.get('type'), 16)))
class_order = {c[0]: i for i, c in enumerate(sorted(classes, key=lambda c: c[3]))}


def class_of(piece_slots):
    for cname, weapon, ability, _ in classes:
        if weapon in piece_slots and ability in piece_slots:
            return cname
    return 'Any'


sets = []
for s in ET.parse(os.path.join(GD, 'equipmentsets')).getroot():
    pieces = list(dict.fromkeys(int(p.get('itemtype'), 16) for p in s.findall('Setpiece')))
    if len(pieces) < 4 or len(pieces) > 5:
        continue
    if not all(i in items and 'ST' in labels(items[i]) for i in pieces):
        continue
    out = []
    for i in pieces:
        alts = sorted(j for j in by_name.get((name(items[i]), slot(items[i])), []) if j != i)
        out.append([i, alts] if alts else [i])
    sets.append({
        'id': int(s.get('type'), 16),
        'name': s.get('id'),
        'cls': class_of({slot(items[i]) for i in pieces}),
        'pieces': out,
    })

sets.sort(key=lambda x: (class_order.get(x['cls'], 999), x['name'].lower()))

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/**\n * ST sets for the ST Set Collection tracker\n')
    f.write(' * Generated by tools/datagen/build_stsets.py from the RotMG Exalt client data (%s)\n' % time.strftime('%Y-%m-%d'))
    f.write(' * {id, name, cls, pieces: [[itemId, [alternate itemIds...]], ...]}\n */\n\n')
    f.write('window.stSets = [\n')
    f.write(',\n'.join('  ' + json.dumps(x, separators=(',', ':')) for x in sets))
    f.write('\n];\n')

print('%d ST sets written to %s' % (len(sets), OUT))
